CREATE TABLE IF NOT EXISTS clientes (
 id BIGSERIAL PRIMARY KEY, nome VARCHAR(140) NOT NULL, documento VARCHAR(30), telefone VARCHAR(40), email VARCHAR(140), cidade VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS motoristas (
 id BIGSERIAL PRIMARY KEY, nome VARCHAR(140) NOT NULL, documento VARCHAR(30), telefone VARCHAR(40), cnh VARCHAR(40), status VARCHAR(30) DEFAULT 'Ativo'
);
CREATE TABLE IF NOT EXISTS veiculos (
 id BIGSERIAL PRIMARY KEY, placa VARCHAR(12) NOT NULL UNIQUE, modelo VARCHAR(100) NOT NULL, tipo VARCHAR(60), capacidade VARCHAR(60), status VARCHAR(30) DEFAULT 'Disponível'
);
CREATE TABLE IF NOT EXISTS cargas (
 id BIGSERIAL PRIMARY KEY, codigo VARCHAR(40) NOT NULL UNIQUE, origem VARCHAR(160) NOT NULL, destino VARCHAR(160) NOT NULL,
 cliente_id BIGINT REFERENCES clientes(id), motorista_id BIGINT REFERENCES motoristas(id), veiculo_id BIGINT REFERENCES veiculos(id),
 cliente VARCHAR(140), motorista VARCHAR(140), veiculo VARCHAR(100), status VARCHAR(40) NOT NULL DEFAULT 'Pendente',
 previsao_entrega DATE, criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS historico_carga (
 id BIGSERIAL PRIMARY KEY, carga_id BIGINT NOT NULL REFERENCES cargas(id) ON DELETE CASCADE,
 status_anterior VARCHAR(40), novo_status VARCHAR(40) NOT NULL, data_alteracao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
